"""Regenerate data/vulnerable_drivers.tsv from the LOLDrivers project.

Usage:
    python -I tools/update_driver_blocklist.py [path-or-url-to-drivers.json]

With no argument it downloads the LOLDrivers API dump from GitHub. Each output line is
    <sha256> <TAB> <category> <TAB> <name>
where category is "vulnerable driver" or "malicious". AEGIS-DRV-001/002/003 match the
SHA-256 of driver files on disk against this list (roadmap A3).

The Microsoft vulnerable driver blocklist (SiPolicy) uses Authenticode page hashes and
signer rules rather than file hashes, so it is not merged here; AEGIS-SYS-005 instead
reports when that blocklist is turned off.
"""
import json
import pathlib
import sys
import urllib.request

DEFAULT_URL = "https://raw.githubusercontent.com/magicsword-io/LOLDrivers/main/loldrivers.io/content/api/drivers.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "vulnerable_drivers.tsv"


def load(src: str):
    if src.startswith("http"):
        with urllib.request.urlopen(src, timeout=120) as r:
            return json.load(r)
    return json.loads(pathlib.Path(src).read_text(encoding="utf-8"))


def clean(s: str) -> str:
    return " ".join(str(s or "").replace("\t", " ").split())[:80]


def main() -> int:
    data = load(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_URL)
    rows = {}
    for entry in data:
        category = clean(entry.get("Category", "")).lower() or "vulnerable driver"
        tags = entry.get("Tags") or []
        default_name = clean(tags[0]) if tags else ""
        for sample in entry.get("KnownVulnerableSamples") or []:
            digest = (sample.get("SHA256") or "").strip().lower()
            if len(digest) != 64:
                continue
            name = clean(sample.get("Filename")) or default_name or clean(sample.get("OriginalFilename"))
            # "malicious" wins if a hash appears under both categories.
            if digest not in rows or category == "malicious":
                rows[digest] = (category, name)
    lines = [
        "# Generated by tools/update_driver_blocklist.py from LOLDrivers (https://www.loldrivers.io). Do not edit.",
        "# sha256\tcategory\tname",
    ]
    lines += [f"{h}\t{c}\t{n}" for h, (c, n) in sorted(rows.items())]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} hashes to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
